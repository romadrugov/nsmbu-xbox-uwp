#!/usr/bin/env python3
"""Create Windows MSVC x64 COFF objects from a *strict* private R2.4 leaf on Mac.

Apple Clang has no Windows SDK headers. This uses an explicitly narrow,
freestanding header derived from the production Cpu declaration in ppc.h.
It supports PPC_ENTER only; any other helper calls fail closed.

Input/output are all LOCAL and outside the public Git checkout.
This is a COFF compile diagnostic, NOT a Windows UWP link or Xbox execution.
"""
import argparse
import json
from pathlib import Path
import re
import shutil
import struct
import subprocess
import sys

import private_gamecode

ROOT = Path(__file__).resolve().parents[2]
PPC = ROOT / "runtime" / "include" / "ppc.h"
TYPE = re.compile(r"typedef struct Cpu \{.*?\} Cpu;", re.S)
CALL = re.compile(r"(?<![\w])([A-Za-z_]\w*)\s*\(")
HEADER = '#include "ppc.h"'

SHIM = r"""/* Generated for a single register-only R2.4 leaf.
   Cpu declaration is copied from production runtime/include/ppc.h.
   Only PPC_ENTER is supported. This shim does not provide guest memory,
   math, string, HLE, graphics, exceptions, or a Windows SDK. */
#ifndef R24_PORTABLE_PPC_H
#define R24_PORTABLE_PPC_H
typedef unsigned char uint8_t;
typedef unsigned short uint16_t;
typedef unsigned int uint32_t;
typedef unsigned long long uint64_t;
_CPU_DECL_
typedef void (*PpcFunc)(Cpu*);
extern int g_ppc_trace;
extern volatile int g_core_preempt[3];
void ppc_trace_enter(uint32_t addr);
void ppc_preempt(Cpu* cpu);
#define PPC_ENTER(a) do { \
    if (__builtin_expect(g_ppc_trace, 0)) ppc_trace_enter(a); \
    if (__builtin_expect(g_core_preempt[c->core], 0)) ppc_preempt(c); \
} while (0)
_Static_assert(sizeof(uint32_t) == 4, "uint32_t ABI");
_Static_assert(sizeof(void*) == 8, "Windows x64 ABI");
_Static_assert(__builtin_offsetof(Cpu, r) == 0, "Cpu.r ABI");
_Static_assert(__builtin_offsetof(Cpu, lr) == 128, "Cpu.lr ABI");
_Static_assert(__builtin_offsetof(Cpu, f) == 176, "Cpu.f ABI");
_Static_assert(__builtin_offsetof(Cpu, pc) == 732, "Cpu.pc ABI");
_Static_assert(__builtin_offsetof(Cpu, core) == 736, "Cpu.core ABI");
_Static_assert(__builtin_offsetof(Cpu, thread) == 744, "Cpu.thread ABI");
_Static_assert(sizeof(Cpu) == 752, "Cpu sizeof ABI");
#endif
"""


def checked_dir(path):
    path = Path(path).expanduser().resolve()
    if not path.is_dir() or private_gamecode.inside_repo(path):
        raise ValueError("private directory must exist outside public repository")
    return path


def checked_cpp(source, allowed_calls):
    if source.count(HEADER) != 1:
        raise ValueError("expected exactly one original ppc.h include")
    # No other headers may enter the freestanding translation units.
    if len(re.findall(r"(?m)^\s*#\s*include\b", source)) != 1:
        raise ValueError("other includes are unsafe without Windows SDK")
    # C is generated by the strict selector. No arbitrary host/helper calls.
    calls = set(CALL.findall(source))
    extra = calls - set(allowed_calls)
    if extra:
        raise ValueError("unapproved standalone leaf helper call(s): " + ", ".join(sorted(extra)))
    if re.search(r"\b(?:ld8|ld16|ld32|ld64|st8|st16|st32|st64|"
                 r"ldf32|ldf64|stf32|stf64|memcpy|memset|"
                 r"ppc_unimplemented|ppc_dispatch|imp_\w+|hook_\w+)\b", source):
        raise ValueError("selected C requires guest memory/runtime APIs")
    return source.replace(HEADER, '#include "r24_portable_ppc.h"', 1)


def build(private, compiler):
    private = checked_dir(private)
    selected = json.loads((private / "selected.json").read_text(encoding="utf-8"))
    witness = json.loads((private / "r24_reference_result.json").read_text(encoding="utf-8"))
    if not witness.get("reference_executed_locally"):
        raise ValueError("run the local Mac reference first")
    if selected["address"] != witness["address"]:
        raise ValueError("selected address and reference result disagree")
    if selected.get("risk") not in (
        "straight-line-register-only",
        "register-only-no-branch-no-guest-memory",
    ):
        raise ValueError("only strict register-only leaf selection is accepted")

    original = PPC.read_text(encoding="utf-8")
    cpu = TYPE.search(original)
    if not cpu:
        raise ValueError("production Cpu declaration not recognized")
    if "thread;" not in cpu.group():
        raise ValueError("production Cpu ABI has changed")
    shim = SHIM.replace("_CPU_DECL_", cpu.group())
    out = private / "r24_coff"
    out.mkdir(exist_ok=True)
    (out / "r24_portable_ppc.h").write_text(shim, encoding="utf-8")

    # Whitelisted public syntactic interface only; actual selected bytes stay local.
    selected_c = checked_cpp(
        (private / "r24_selected.c").read_text(encoding="utf-8"),
        {"nsmbu_r24_private_function", "PPC_ENTER"},
    )
    binding_c = checked_cpp(
        (private / "r24_private_binding.c").read_text(encoding="utf-8"),
        {"nsmbu_r24_private_function"},
    )
    (out / "r24_selected.c").write_text(selected_c, encoding="utf-8")
    (out / "r24_private_binding.c").write_text(binding_c, encoding="utf-8")

    clang = shutil.which(compiler)
    if not clang:
        raise ValueError("compiler not found: " + compiler)
    for basename in ("r24_selected", "r24_private_binding"):
        src = out / (basename + ".c")
        obj = private / (basename + ".obj")
        command = [
            clang, "--target=x86_64-pc-windows-msvc",
            "-std=c11", "-O2", "-ffreestanding", "-nostdinc",
            "-I", str(out), "-c", str(src), "-o", str(obj)
        ]
        subprocess.run(command, check=True, cwd=out)
        # 0x8664 is AMD64 IMAGE_FILE_MACHINE_AMD64 in COFF header.
        raw = obj.read_bytes()
        if len(raw) < 20 or struct.unpack_from("<H", raw)[0] != 0x8664:
            raise ValueError(basename + " is not an x64 COFF object")
        print("Windows x64 COFF PASS:", obj.name, "(%d bytes)" % len(raw))
    print("Both objects are private Windows x64 COFF; Mac compiled only.")
    print("NOT verified yet: MSVC UWP link, application packaging, Xbox run.")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--private", required=True, help="private R2.4 output directory")
    parser.add_argument("--compiler", default="clang")
    args = parser.parse_args()
    try:
        build(args.private, args.compiler)
    except (OSError, ValueError, KeyError, subprocess.CalledProcessError, json.JSONDecodeError) as exc:
        parser.exit(1, "R2.4 COFF stopped: %s\n" % exc)


if __name__ == "__main__":
    main()
