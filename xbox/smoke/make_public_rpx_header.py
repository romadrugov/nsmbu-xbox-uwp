#!/usr/bin/env python3
"""Generate public fixture bytes + known RPX SHA256 fingerprints for UWP CI.

Input comes only from recomp/android_fixture.py (three instructions),
and hashes from recomp/builds.py (no game content). No Nintendo data is
included in the generated header or app package.
"""
import argparse
from pathlib import Path
import sys


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("synthetic_rpx", type=Path)
    parser.add_argument("header", type=Path)
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[2]
    sys.path.insert(0, str(root / "recomp"))
    from builds import all_builds

    data = args.synthetic_rpx.read_bytes()
    if len(data) > 4096 or data[:4] != b"\x7fELF":
        raise ValueError("the public synthetic fixture has unexpected content")
    builds = all_builds()
    out = [
        "#pragma once",
        "// Generated by make_public_rpx_header.py: public synthetic test RPX only.",
        "// Known-build entries contain SHA256 fingerprints, NOT game data.",
        "#include <cstddef>",
        "#include <cstdint>",
        "namespace xboxrpxfixture {",
        "inline constexpr uint8_t kSyntheticRpx[] = {",
    ]
    for offset in range(0, len(data), 16):
        out.append("    " + ", ".join(f"0x{value:02x}" for value in data[offset:offset+16]) + ",")
    out += [
        "};",
        "struct KnownBuild { const char* name; const char* sha256; };",
        "inline constexpr KnownBuild kKnownBuilds[] = {",
    ]
    for build in builds:
        if len(build.sha256) != 64:
            raise ValueError("invalid known hash")
        out.append(f'    {{"{build.name}", "{build.sha256}"}},')
    out += ["};", "} // namespace xboxrpxfixture", ""]
    args.header.parent.mkdir(parents=True, exist_ok=True)
    args.header.write_text("\n".join(out), encoding="utf-8")
    print(f"Public synthetic RPX {len(data)} bytes; known SHA fingerprints {len(builds)}")


if __name__ == "__main__":
    main()
